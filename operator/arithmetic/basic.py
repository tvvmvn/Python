# + Addition: x + y 
# - Subtraction: x - y 
# * Multiplication: x * y 
# / Division: x / y 
# // Floor division: x // y
# % Modulus: x % y 
# ** Exponentiation: x ** y 

x = 15
y = 4

print(x + y)
print(x - y)
print(x * y)
print(x / y) # Division (returns a float)
print(x // y) # Floor division (returns an integer)
print(x % y)
print(x ** y)